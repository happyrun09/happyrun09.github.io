// Chuyển đổi dữ liệu sang định dạng chuẩn của thư viện mã nguồn mở donatso/family-chart
window.buildFamilyChartData = function () {
  const nodes = {};
  const ensureNode = (id, data, rels = {}) => {
    nodes[id] = {
      id,
      data,
      rels: {
        parents: rels.parents || [],
        spouses: rels.spouses || [],
        children: rels.children || []
      }
    };
  };

  window.MEMBERS.forEach(m => {
    ensureNode(m.id, {
      "full name": m.name,
      "gen": `Đời ${m.gen}`,
      "dates": [m.birth ? `Sinh: ${m.birth}` : "", m.death ? `Mất: ${m.death}` : ""].filter(Boolean).join(" • ") || (m.role || ""),
      "gender": m.gender || "M",
      "rawId": m.id
    });
  });

  // Gắn quan hệ cha-con và vợ-chồng
  window.MEMBERS.forEach(m => {
    const node = nodes[m.id];
    if (m.parentId && nodes[m.parentId]) {
      const parent = nodes[m.parentId];
      if (!node.rels.parents.includes(m.parentId)) node.rels.parents.push(m.parentId);
      if (!parent.rels.children.includes(m.id)) parent.rels.children.push(m.id);
    }
    if (m.spouses && m.spouses.length > 0) {
      m.spouses.forEach((sp, idx) => {
        const spId = `${m.id}_sp_${idx}`;
        const spGender = m.gender === "M" ? "F" : "M";
        ensureNode(spId, {
          "full name": sp.name,
          "gen": `Phối ngẫu Đời ${m.gen}`,
          "dates": [sp.birth ? `Sinh: ${sp.birth}` : "", sp.death ? `Mất: ${sp.death}` : ""].filter(Boolean).join(" • ") || (sp.note || "Phối ngẫu"),
          "gender": spGender,
          "rawId": m.id
        }, {
          spouses: [m.id],
          children: idx === 0 ? [...node.rels.children] : []
        });
        node.rels.spouses.push(spId);
      });
    }
  });

  // Liên kết con với người vợ/chồng đầu tiên để family-chart vẽ đường nối cặp đôi chuẩn xác
  window.MEMBERS.forEach(m => {
    if (m.parentId && nodes[m.parentId]) {
      const pNode = nodes[m.parentId];
      if (pNode.rels.spouses.length > 0) {
        const firstSpouseId = pNode.rels.spouses[0];
        if (!nodes[m.id].rels.parents.includes(firstSpouseId)) {
          nodes[m.id].rels.parents.push(firstSpouseId);
        }
        if (!nodes[firstSpouseId].rels.children.includes(m.id)) {
          nodes[firstSpouseId].rels.children.push(m.id);
        }
      }
    }
  });

  return Object.values(nodes);
};

